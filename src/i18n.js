  const RTL = new Set(['fa', 'ar']);
  let current = 'en';

  function t(key) { return (DICT[current] && DICT[current][key]) || DICT.en[key] || key; }

  function apply(lang) {
    current = DICT[lang] ? lang : 'en';
    document.documentElement.lang = current;
    document.documentElement.dir = RTL.has(current) ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  }

  function detect() {
    const n = (navigator.language || 'en').toLowerCase();
    if (n.startsWith('fa')) return 'fa';
    if (n.startsWith('ar')) return 'ar';
    if (n.startsWith('ru')) return 'ru';
    return 'en';
  }
  function tf(key, vars) {
    let out = t(key);
    Object.keys(vars || {}).forEach((k) => { out = out.replace('{' + k + '}', vars[k]); });
    return out;
  }

  return { t, tf, detect, apply, get current() { return current; }, langs: Object.keys(DICT) };
